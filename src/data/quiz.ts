// Les cartes « Que signifie ce panneau ? » (pim-1, pim-2…) ont pour choix des
// noms de panneaux : leur version malagasy se déduit des noms malagasy des
// panneaux, au lieu d'être recopiée à la main.
const signByName = new Map(panneaux.map((p) => [p.name, p]));

function signCardMg(q: QuizQuestion): QuizQuestion['mg'] {
  const sign = panneaux.find((p) => p.id === q.sign);
  if (!sign?.mg) return undefined;
  const choices = q.choices.map((c) => signByName.get(c)?.mg?.name);
  if (choices.some((c) => !c)) return undefined;
  return {
    question: sign.category === 'special' ? "Inona no dikan'ity jiro ity ?" : "Inona no dikan'ity famantarana ity ?",
    choices: choices as string[],
    explanation: `${sign.mg.name} — ${sign.mg.description}`,
  };
}

export const quizModules: QuizModule[] = quizModulesFr.map((mod) => ({
  ...mod,
  titleMg: quizTitleMg[mod.slug],
  questions: mod.questions.map((q) => ({
    ...q,
    mg: quizMg[q.id] ?? (/^pim-\d+$/.test(q.id) ? signCardMg(q) : undefined),
  })),
}));

export function getQuizModule(slug: string) {
  return quizModules.find((m) => m.slug === slug);
}

/**
 * Questions prêtes à être sérialisées vers Alpine : le panneau éventuel est
 * converti en balisage (`signHtml`), que les pages affichent avec x-html.
 */
export function withSignVisuals<T extends QuizQuestion>(questions: T[]): (T & { signHtml?: string })[] {
  return questions.map((q) => {
    const sign = q.sign ? panneaux.find((p) => p.id === q.sign) : undefined;
    return sign ? { ...q, signHtml: signHtml(sign) } : q;
  });
}
