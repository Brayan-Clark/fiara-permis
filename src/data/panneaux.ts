// Feu tricolore dessiné : `lit` = feu allumé, `arrow` = flèche verte (4e feu),
// `blink` = jaune clignotant (animation coupée si l'utilisateur réduit les
// animations, et figée allumée à l'impression).
function trafficLight(lit: 'red' | 'amber' | 'green' | 'arrow' | 'blink'): string {
  const on = (c: string, k: string) => (lit === k || (k === 'amber' && lit === 'blink') ? c : OFF);
  const blink =
    lit === 'blink'
      ? `<style>@keyframes fiara-blink{50%{opacity:.15}}.fiara-blink{animation:fiara-blink 1.2s steps(1) infinite}@media (prefers-reduced-motion:reduce),print{.fiara-blink{animation:none}}</style>`
      : '';
  // Rayons autour du jaune : le clignotement reste lisible sur une image figée.
  const rays =
    lit === 'blink'
      ? `<g class="fiara-blink" stroke="${AMBER}" stroke-width="4" stroke-linecap="round"><path d="M22 50 H28 M72 50 H78 M27 37 L32 41 M73 37 L68 41 M27 63 L32 59 M73 63 L68 59"/></g>`
      : '';
  const arrow =
    lit === 'arrow'
      ? `<rect x="64" y="66" width="22" height="22" rx="4" fill="${INK}"/><path d="M69 77 H81 M76 71 L82 77 L76 83" stroke="${GREEN}" stroke-width="3" fill="none" stroke-linecap="round" stroke-linejoin="round"/>`
      : '';
  return `<svg viewBox="0 0 100 100" xmlns="http://www.w3.org/2000/svg">${blink}<rect x="34" y="4" width="32" height="92" rx="8" fill="${INK}"/><circle cx="50" cy="22" r="11" fill="${on(RED, 'red')}"/><circle cx="50" cy="50" r="11" fill="${on(AMBER, 'amber')}"${lit === 'blink' ? ' class="fiara-blink"' : ''}/><circle cx="50" cy="78" r="11" fill="${on(GREEN, 'green')}"/>${arrow}${rays}</svg>`;
}

/**
 * Balisage HTML d'un panneau : l'image officielle (chargée depuis public/) ou
 * le dessin en ligne. Toujours décoratif côté accessibilité : le nom du
 * panneau est écrit à côté.
 */
export function signHtml(sign: RoadSign): string {
  if (sign.svg) return sign.svg;
  const base = (import.meta.env.BASE_URL ?? '/').replace(/\/$/, '');
  return `<img src="${base}/panneaux/${sign.id}.svg" alt="" loading="lazy" decoding="async" class="h-full w-full object-contain" />`;
}

